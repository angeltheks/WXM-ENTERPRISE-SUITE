function normalizeLanguage(value) {
    const code = String(value || '').toLowerCase();
    if (code.startsWith('en')) return 'en';
    return 'es';
}

export function createI18n(options = {}) {
    const supported = Array.isArray(options.supportedLanguages) ? options.supportedLanguages : ['es', 'en'];
    let preference = localStorage.getItem(STORAGE_KEY) || options.defaultLanguage || 'system';

    const resolve = () => {
        if (supported.includes(preference) && preference !== 'system') return preference;
        return normalizeLanguage(navigator.language || navigator.userLanguage || 'es');
    };

    const t = (key, fallback = '') => {
        const lang = resolve();
        return DICTIONARIES[lang]?.[key] || DICTIONARIES.es[key] || fallback || key;
    };

    const setPreference = (nextPreference) => {
        preference = ['system', ...supported].includes(nextPreference) ? nextPreference : 'system';
        localStorage.setItem(STORAGE_KEY, preference);
        document.documentElement.lang = resolve();
        window.dispatchEvent(new CustomEvent('wxm-language-changed', {
            detail: { language: resolve(), preference }
        }));
    };

    document.documentElement.lang = resolve();

    return {
        t,
        resolve,
        getPreference: () => preference,
        setPreference,
        options: [
            { id: 'system', labelKey: 'common.system' },
            { id: 'es', labelKey: 'common.spanish' },
            { id: 'en', labelKey: 'common.english' }
        ]
    };
}

